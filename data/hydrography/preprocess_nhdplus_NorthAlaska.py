#!/usr/bin/env python3

"""
Preprocess hydrography data sourced from NHDPlus / reference hydrofabric
layers (flowpaths, divides, lakes) for FIM ingestion.
Spatially filters shared multi-region datasets using the preprocessed regional WBD boundary.
"""

import argparse
import os
import sys

import geopandas as gpd
from rasterio.crs import CRS

from data.derive_headwaters import findHeadWaterPoints


def preprocess_nhdplus(region, hucs, target_crs_number, inputs_dir, reference_fabric_file, date):
    """
    Preprocess NHDPlus / reference hydrofabric vector datasets for a region.

    Parameters:
    -----------
    region : str
        Region identifier (e.g., 'Fairbanks', 'Juneau').
    hucs : list of str
        Target HUC8 IDs for reference.
    target_crs_number : str or int
        Target EPSG projection number (e.g., '3338').
    inputs_dir : str
        Base inputs directory containing reference layers.
    reference_fabric_file : str
        Path to input shared reference hydrofabric GPKG file.
    date : str
        Run date identifier.
    """
    if not os.path.exists(reference_fabric_file):
        sys.exit(f"ERROR: Reference fabric file {reference_fabric_file} does not exist. Exiting...")

    reference_fabric_folder = os.path.dirname(reference_fabric_file)
    target_crs = CRS.from_epsg(int(target_crs_number))

    # 1. Read regional WBD boundary previously generated by preprocess_wbd
    wbd_file = os.path.join(inputs_dir, "wbd", f"WBD_{region}_{target_crs_number}.gpkg")
    if not os.path.exists(wbd_file):
        sys.exit(
            f"ERROR: Regional WBD boundary {wbd_file} does not exist. " "Please run preprocess_wbd first."
        )

    print(f"[{region}] Reading regional spatial mask from {wbd_file}...")
    region_wbd = gpd.read_file(wbd_file, layer="WBDHU8")
    if region_wbd.crs != target_crs:
        region_wbd = region_wbd.to_crs(epsg=target_crs_number)
    region_mask = region_wbd.unary_union

    # 2. Flowpaths: Read, reproject, subset to region, and derive headwaters
    print(f"[{region}] Loading and subsetting flowpaths...")
    flowpaths = gpd.read_file(reference_fabric_file, layer="flowpaths")
    if flowpaths.crs != target_crs:
        flowpaths = flowpaths.to_crs(epsg=target_crs_number)

    flowpaths = flowpaths[flowpaths.intersects(region_mask)].copy()
    if flowpaths.empty:
        print(f"Warning: No flowpaths intersected regional boundary for {region}.")

    flowpaths = flowpaths.rename(
        columns={"flowpath_id": "ID", "flowpath_toid": "to", "streamorder": "order_"}
    )

    print(f"[{region}] Deriving headwater points for {len(flowpaths)} flowpaths...")
    headwater_points = findHeadWaterPoints(flowpaths)
    headwater_points.to_file(
        os.path.join(reference_fabric_folder, f"flowpaths_headwaters_{region}.gpkg"), driver="GPKG"
    )

    # 3. Lakes: Read, reproject, and subset
    print(f"[{region}] Loading and subsetting lakes...")
    lakes = gpd.read_file(reference_fabric_file, layer="lakes")
    lakes = lakes.rename(columns={"Hylak_id": "LakeID"})
    if lakes.crs != target_crs:
        lakes = lakes.to_crs(epsg=target_crs_number)

    lakes = lakes[lakes.intersects(region_mask)].copy()
    lakes = lakes[["LakeID", "geometry"]]
    lakes.to_file(os.path.join(reference_fabric_folder, f"lakes_{region}.gpkg"), driver="GPKG")

    # Spatial join lakes onto flowpaths
    flowpaths = flowpaths.sjoin(lakes, how="left", predicate="intersects")
    flowpaths = flowpaths.rename(columns={"LakeID": "Lake"})
    flowpaths["Lake"] = flowpaths["Lake"].fillna(-9999).astype(int)

    if "index_right" in flowpaths.columns:
        flowpaths = flowpaths.drop(columns=["index_right"])
    flowpaths = flowpaths.drop_duplicates(subset=["ID"])

    flowpaths.to_file(os.path.join(reference_fabric_folder, f"flowpaths_{region}.gpkg"), driver="GPKG")

    # 4. Catchments / Divides: Read, reproject, and subset
    print(f"[{region}] Loading and subsetting catchments...")
    catchments = gpd.read_file(reference_fabric_file, layer="divides")
    catchments = catchments.rename(columns={"divide_id": "ID"})
    if catchments.crs != target_crs:
        catchments = catchments.to_crs(epsg=target_crs_number)

    catchments = catchments[catchments.intersects(region_mask)].copy()
    catchments.to_file(os.path.join(reference_fabric_folder, f"catchments_{region}.gpkg"), driver="GPKG")

    print(f"[{region}] Hydrography vector preprocessing completed.")


def main():
    parser = argparse.ArgumentParser(
        description="Preprocess NHDPlus / reference hydrofabric vector datasets for a specific region."
    )
    parser.add_argument(
        "-r", "--region", type=str, required=True, help="Region identifier (e.g., 'Fairbanks', 'Juneau')"
    )
    parser.add_argument(
        "-u",
        "--hucs",
        nargs="+",
        required=True,
        help="Space-separated list of target HUC8 IDs (e.g., -u 19080306 19080307)",
    )
    parser.add_argument(
        "-i",
        "--inputs_dir",
        type=str,
        required=True,
        help="Base inputs directory containing reference layers (e.g., /data/inputs)",
    )
    parser.add_argument(
        "-s",
        "--reference_fabric_file",
        type=str,
        required=True,
        help="Path to shared reference hydrofabric GPKG file",
    )
    parser.add_argument(
        "-c",
        "--target_crs_number",
        type=str,
        required=False,
        default="3338",
        help="Target EPSG projection number (default: 3338)",
    )
    parser.add_argument(
        "-d", "--date", type=str, required=True, help="Run identifier date string (e.g., 20261026)"
    )

    args = parser.parse_args()

    preprocess_nhdplus(
        region=args.region,
        hucs=args.hucs,
        target_crs_number=args.target_crs_number,
        inputs_dir=args.inputs_dir,
        reference_fabric_file=args.reference_fabric_file,
        date=args.date,
    )
